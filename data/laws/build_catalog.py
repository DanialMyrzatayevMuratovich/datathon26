def norm(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


def main() -> None:
    texts = {}
    for code, meta in ACTS.items():
        df = pd.read_csv(HERE / meta["csv"], dtype=str)
        texts[code] = {}
        for p, t in zip(df["point"], df["text"]):  # first occurrence = main body; appendices reuse numbers
            texts[code].setdefault(p, norm(t))
    out, problems = [], []
    for type_id, type_name, refs, why in CATALOG:
        items = []
        for act, point, sub, quote, basis in refs:
            body = texts[act].get(point)
            if body is None:
                problems.append(f"{type_id}: нет пункта {point} в акте {act}")
                continue
            if norm(quote) not in body:
                problems.append(f"{type_id}: цитата не найдена дословно в п.{point} акта {act}: {quote[:60]}…")
            meta = ACTS[act]
            items.append({
                "act": meta["title"], "approved": meta["approved"], "url": meta["url"],
                "point": point, "subpoint": sub,
                "ref": f"п. {point}" + (f", подп. {sub})" if sub else ""),
                "quote": norm(quote), "basis": basis,
            })
        out.append({"type_id": type_id, "type": type_name, "why": why, "rules": items})
    if problems:
        raise SystemExit("✖ каталог не собран:\n" + "\n".join(problems))
    (HERE / "rules_catalog.json").write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    direct = sum(any(r["basis"] == "direct" for r in t["rules"]) for t in out)
    print(f"✔ rules_catalog.json: {len(out)} типов, все цитаты дословные; прямая норма у {direct}, трактовка у "
          f"{len(out) - direct}")


if __name__ == "__main__":
    main()
